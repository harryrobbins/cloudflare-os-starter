// Writes the data dictionary section of src/SKILL.md from the dataset registry, so the agent's
// skill always documents the datasets the server actually offers. `--check` exits 1 when stale.
//
//   node scripts/skill-dictionary.mjs [--check]

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { listDatasets } from "../src/shared/datasets/index.js";

const file = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "SKILL.md");
const START = "<!-- dictionary:start (generated by `node scripts/skill-dictionary.mjs`; do not edit by hand) -->";
const END = "<!-- dictionary:end -->";

export function dictionary() {
  return listDatasets().map((d) => [
    `### \`${d.name}\`: ${d.title}`,
    "",
    d.description,
    "",
    Object.keys(d.params).length ? `Parameters: ${Object.entries(d.params).map(([k, v]) => `\`${k}\` (${v})`).join("; ")}.` : "No parameters.",
    "",
    "| Column | Type | Meaning |",
    "| --- | --- | --- |",
    ...d.columns.map((c) => `| \`${c.name}\` | ${c.type} | ${c.description.replace(/\|/g, "\\|")} |`),
    "",
  ].join("\n")).join("\n");
}

/** @param {string} text */
export function withDictionary(text) {
  const a = text.indexOf(START), b = text.indexOf(END);
  if (a === -1 || b === -1) throw new Error("SKILL.md has no dictionary markers");
  return `${text.slice(0, a + START.length)}\n\n${dictionary()}\n${text.slice(b)}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = await readFile(file, "utf8");
  const next = withDictionary(text);
  if (process.argv.includes("--check")) {
    if (next !== text) { console.error("src/SKILL.md data dictionary is stale; run node scripts/skill-dictionary.mjs"); process.exit(1); }
    console.log("SKILL.md dictionary is current");
  } else {
    await writeFile(file, next);
    console.log("updated", file);
  }
}
