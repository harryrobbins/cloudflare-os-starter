// Code generation for the Records SDKs from the OpenAPI document (pure functions; generate.ts
// writes the files, and __tests__/generate.test.ts checks the committed output is current).
//
// What is generated, from the document alone:
//   TypeScript  src/generated/types.ts   one type per component schema, one query type per operation
//               src/generated/client.ts  the operation table and `RecordsClient`, one method per
//                                        operation plus an async iterator per paginated operation
//   Python      python/records_sdk/_generated.py  TypedDicts, the operation table and the client
// The runtime behaviour (idempotency keys, retries, Retry-After, 412 → RevisionConflictError) lives in
// hand-written runtimes (src/runtime.ts, python/records_sdk/_runtime.py) driven by the operation
// table's `x-records-*` extensions, so both languages behave the same.

type Schema = Record<string, any>;
type Doc = { paths: Record<string, Record<string, any>>; components: { schemas: Record<string, Schema>; parameters: Record<string, any> }; info: { version: string } };

export type Operation = {
  id: string;
  method: string;
  /** Path with `{datastoreId}` and other placeholders. */
  path: string;
  summary: string;
  pathParams: string[];
  query: { name: string; schema: Schema; description?: string }[];
  body: string | null;
  response: string | null;
  idempotency: "safe" | "key" | "natural";
  ifMatch: boolean;
  pagination: Record<string, string> | null;
};

const HEADER = "Generated by packages/records-sdk/scripts/generate.ts from the Records OpenAPI document. Do not edit.";

export function operations(doc: Doc): Operation[] {
  const out: Operation[] = [];
  for (const [path, item] of Object.entries(doc.paths)) {
    for (const [method, op] of Object.entries(item)) {
      if (op["x-records-sdk"] === false) continue;
      const params = (op.parameters ?? []).map((p: any) => (p.$ref ? doc.components.parameters[p.$ref.split("/").pop()] : p));
      const success = Object.entries(op.responses as Record<string, any>).find(([s]) => s.startsWith("2"))?.[1];
      const responseRef: string | undefined = success?.content?.["application/json"]?.schema?.$ref;
      const bodyRef: string | undefined = op.requestBody?.content?.["application/json"]?.schema?.$ref;
      out.push({
        id: op.operationId,
        method: method.toUpperCase(),
        path,
        summary: op.summary ?? "",
        pathParams: params.filter((p: any) => p.in === "path" && p.name !== "datastoreId").map((p: any) => p.name),
        query: params.filter((p: any) => p.in === "query").map((p: any) => ({ name: p.name, schema: p.schema, ...(p.description ? { description: p.description } : {}) })),
        body: bodyRef ? bodyRef.split("/").pop()! : null,
        response: responseRef ? responseRef.split("/").pop()! : null,
        idempotency: op["x-records-idempotency"],
        ifMatch: op["x-records-if-match"] === true,
        pagination: op["x-records-pagination"] ?? null,
      });
    }
  }
  return out;
}

const pascal = (s: string) => s[0]!.toUpperCase() + s.slice(1);
const snake = (s: string) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const iteratorName = (id: string) => `iterate${id.replace(/^list/, "")}`;

