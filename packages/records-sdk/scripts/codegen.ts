// Python

function pyType(schema: Schema | undefined): string {
  if (!schema || Object.keys(schema).filter((k) => !["description", "default"].includes(k)).length === 0) return "Any";
  if (schema.$ref) return `"${schema.$ref.split("/").pop()}"`;
  if (schema.anyOf || schema.oneOf) {
    const parts = [...new Set<string>((schema.anyOf ?? schema.oneOf).map((s: Schema) => pyType(s)))];
    return parts.length === 1 ? parts[0]! : `Union[${parts.join(", ")}]`;
  }
  if ("const" in schema) return `Literal[${JSON.stringify(schema.const)}]`;
  if (schema.enum) return `Literal[${schema.enum.map((v: unknown) => JSON.stringify(v)).join(", ")}]`;
  switch (schema.type) {
    case "string": return "str";
    case "integer": return "int";
    case "number": return "float";
    case "boolean": return "bool";
    case "null": return "None";
    case "array": return `List[${pyType(schema.items)}]`;
    case "object": return schema.properties ? "Dict[str, Any]" : `Dict[str, ${schema.additionalProperties && schema.additionalProperties !== true ? pyType(schema.additionalProperties) : "Any"}]`;
    default: return "Any";
  }
}

const PY_KEYWORDS = new Set(["from", "to", "in", "is", "not", "and", "or", "class", "def", "return", "global", "type", "id"]);

export function generatePython(document: Doc): string {
  const out: string[] = [
    `# ${HEADER}`,
    "# ruff: noqa",
    "from __future__ import annotations",
    "",
    "from typing import Any, Dict, Iterator, List, Literal, NotRequired, Optional, TypedDict, Union",
    "",
    "from ._runtime import BaseClient, IfMatch",
    "",
    `API_VERSION = ${JSON.stringify(document.info.version)}`,
    "",
  ];
  // Component types: TypedDicts for objects with properties (functional syntax: field names such
  // as `from` are Python keywords), aliases for the rest.
  for (const [name, schema] of Object.entries(document.components.schemas)) {
    if (schema.type === "object" && schema.properties) {
      const required = new Set<string>(schema.required ?? []);
      const fields = Object.entries(schema.properties as Record<string, Schema>).map(([k, s]) => {
        const t = pyType(s);
        return `    ${JSON.stringify(k)}: ${required.has(k) ? t : `NotRequired[${t}]`},`;
      });
      out.push(`${name} = TypedDict(${JSON.stringify(name)}, {`, ...fields, "})", "");
    } else {
      out.push(`${name} = ${pyType(schema).replace(/^"(.*)"$/, "$1")}`, "");
    }
  }
  const ops = operations(document);
  out.push("OPERATIONS: Dict[str, Dict[str, Any]] = {");
  for (const op of ops) {
    out.push(`    ${JSON.stringify(op.id)}: ${JSON.stringify({ method: op.method, path: op.path, idempotency: op.idempotency, ifMatch: op.ifMatch, pagination: op.pagination })
      .replaceAll(":true", ":True").replaceAll(":false", ":False").replaceAll(":null", ":None")},`);
  }
  out.push("}", "", "", "class RecordsClient(BaseClient):", '    """Typed client for the Records native API, bound to one datastore."""', "");
  for (const op of ops) {
    const args = ["self", ...op.pathParams.map((p) => `${snake(p)}: str`)];
    if (op.body) args.push(`body: ${op.body}`);
    const kw: string[] = [];
    for (const q of op.query) kw.push(`${pyQueryName(q.name)}: Optional[${pyType(q.schema).replace(/^"(.*)"$/, "$1")}] = None`);
    if (op.ifMatch) kw.push("if_match: IfMatch");
    if (op.idempotency === "key") kw.push("idempotency_key: Optional[str] = None");
    const signature = kw.length ? [...args, "*", ...kw] : args;
    const queryDict = op.query.length ? `{${op.query.map((q) => `${JSON.stringify(q.name)}: ${pyQueryName(q.name)}`).join(", ")}}` : "None";
    const pathDict = `{${op.pathParams.map((p) => `${JSON.stringify(p)}: ${snake(p)}`).join(", ")}}`;
    const result = op.response ?? "Any";
    out.push(
      `    def ${snake(op.id)}(${signature.join(", ")}) -> ${result}:`,
      `        """${op.summary}."""`,
      `        return self._call(OPERATIONS[${JSON.stringify(op.id)}], ${pathDict}, ${queryDict}, ${op.body ? "body" : "None"}, ` +
        `if_match=${op.ifMatch ? "if_match" : "None"}, idempotency_key=${op.idempotency === "key" ? "idempotency_key" : "None"})`,
      "",
    );
    if (op.pagination && op.response) {
      const itemRef: string | undefined = document.components.schemas[op.response]!.properties?.[op.pagination.itemsField!]?.items?.$ref;
      const item = itemRef ? itemRef.split("/").pop()! : "Any";
      const iterArgs = [...args.filter((a) => !a.startsWith("body")), ...(op.query.length ? ["*", ...op.query.map((q) => `${pyQueryName(q.name)}: Optional[${pyType(q.schema).replace(/^"(.*)"$/, "$1")}] = None`)] : [])];
      out.push(
        `    def ${snake(iteratorName(op.id))}(${iterArgs.join(", ")}) -> Iterator[${item}]:`,
        `        """Every item of ${snake(op.id)}, page by page."""`,
        `        return self._paginate(OPERATIONS[${JSON.stringify(op.id)}], ${pathDict}, ${queryDict})`,
        "",
      );
    }
  }
  return `${out.join("\n").trimEnd()}\n`;
}

function pyQueryName(name: string): string {
  const s = snake(name);
  return PY_KEYWORDS.has(s) ? `${s}_` : s;
}
