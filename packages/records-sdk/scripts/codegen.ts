// TypeScript

function tsType(schema: Schema | undefined, indent = ""): string {
  if (!schema || Object.keys(schema).filter((k) => !["description", "default"].includes(k)).length === 0) return "unknown";
  if (schema.$ref) return schema.$ref.split("/").pop();
  if (schema.anyOf || schema.oneOf) return (schema.anyOf ?? schema.oneOf).map((s: Schema) => tsType(s, indent)).join(" | ");
  if ("const" in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((v: unknown) => JSON.stringify(v)).join(" | ");
  if (Array.isArray(schema.type)) return schema.type.map((t: string) => tsType({ ...schema, type: t }, indent)).join(" | ");
  switch (schema.type) {
    case "string": return "string";
    case "integer":
    case "number": return "number";
    case "boolean": return "boolean";
    case "null": return "null";
    case "array": {
      const item = tsType(schema.items, indent);
      return /[ |]/.test(item) ? `Array<${item}>` : `${item}[]`;
    }
    case "object": {
      const props = Object.entries((schema.properties ?? {}) as Record<string, Schema>);
      const extra = schema.additionalProperties && schema.additionalProperties !== true ? tsType(schema.additionalProperties, indent) : schema.additionalProperties === false ? null : "unknown";
      if (props.length === 0) return `Record<string, ${extra ?? "never"}>`;
      const required = new Set<string>(schema.required ?? []);
      const inner = `${indent}  `;
      const lines = props.map(([name, s]) => `${doc(s.description, inner)}${inner}${/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name)}${required.has(name) ? "" : "?"}: ${tsType(s, inner)};`);
      return `{\n${lines.join("\n")}\n${indent}}`;
    }
    default: return "unknown";
  }
}

function doc(text: string | undefined, indent: string): string {
  return text ? `${indent}/** ${text.replaceAll("*/", "*\\/").replaceAll("\n", " ")} */\n` : "";
}

export function generateTsTypes(document: Doc): string {
  const lines = [`// ${HEADER}`, ""];
  for (const [name, schema] of Object.entries(document.components.schemas)) {
    lines.push(`${doc(schema.description, "")}export type ${name} = ${tsType(schema)};`, "");
  }
  for (const op of operations(document).filter((o) => o.query.length)) {
    const props = op.query.map((q) => `${doc(q.description, "  ")}  ${q.name}?: ${tsType(q.schema, "  ")};`);
    lines.push(`/** Query parameters of \`${op.id}\`. */`, `export type ${pascal(op.id)}Query = {\n${props.join("\n")}\n};`, "");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

export function generateTsClient(document: Doc): string {
  const ops = operations(document);
  const imports = new Set<string>();
  for (const op of ops) {
    if (op.body) imports.add(op.body);
    if (op.response) imports.add(op.response);
    if (op.query.length) imports.add(`${pascal(op.id)}Query`);
  }
  const table = ops.map((op) => `  ${op.id}: ${JSON.stringify({
    method: op.method, path: op.path, idempotency: op.idempotency, ifMatch: op.ifMatch, pagination: op.pagination,
  })},`);
  const methods: string[] = [];
  for (const op of ops) {
    const params: string[] = op.pathParams.map((p) => `${p}: string`);
    if (op.query.length) params.push(`query: ${pascal(op.id)}Query = {}`);
    if (op.body) params.push(`body: ${op.body}`);
    const optionsType = op.ifMatch ? "WriteOptions & { ifMatch: IfMatch }" : op.idempotency === "key" ? "WriteOptions" : "CallOptions";
    params.push(op.ifMatch ? `options: ${optionsType}` : `options: ${optionsType} = {}`);
    const result = op.response ?? "unknown";
    const pathArg = op.pathParams.length ? `{ ${op.pathParams.join(", ")} }` : "{}";
    methods.push(
      `  /** ${op.summary}. \`${op.method} ${op.path.replace("/gatekeeper/records/v1", "")}\` */`,
      `  ${op.id}(${params.join(", ")}): Promise<${result}> {`,
      `    return this.call<${result}>(OPERATIONS.${op.id}, ${pathArg}, ${op.query.length ? "query" : "undefined"}, ${op.body ? "body" : "undefined"}, options);`,
      "  }",
      "",
    );
    if (op.pagination && op.response) {
      const page = document.components.schemas[op.response]!;
      const itemsField = op.pagination.itemsField!;
      const itemRef: string | undefined = page.properties?.[itemsField]?.items?.$ref;
      const item = itemRef ? itemRef.split("/").pop()! : "unknown";
      if (itemRef) imports.add(item);
      const iterParams = [...op.pathParams.map((p) => `${p}: string`), `query: ${pascal(op.id)}Query = {}`, "options: CallOptions = {}"];
      const cursorName = op.pagination.style === "cursor" ? op.pagination.cursorParam : op.pagination.afterParam;
      methods.push(
        op.pagination.style === "cursor"
          ? `  /** Every item of \`${op.id}\`, following \`${op.pagination.nextField}\` page by page. */`
          : `  /** Every entry of \`${op.id}\` after \`query.${cursorName}\` up to the head at the time of each page. */`,
        `  ${iteratorName(op.id)}(${iterParams.join(", ")}): AsyncGenerator<${item}> {`,
        `    return this.paginate<${item}>(OPERATIONS.${op.id}, ${pathArg}, query, options);`,
        "  }",
        "",
      );
    }
  }
  return [
    `// ${HEADER}`,
    "",
    `import { BaseClient, type CallOptions, type IfMatch, type OperationSpec, type WriteOptions } from "../runtime.js";`,
    `import type { ${[...imports].sort().join(", ")} } from "./types.js";`,
    "",
    `/** The API version this client was generated from. */`,
    `export const API_VERSION = ${JSON.stringify(document.info.version)};`,
    "",
    "export const OPERATIONS = {",
    ...table,
    "} as const satisfies Record<string, OperationSpec>;",
    "",
    "/** Typed client for the Records native API, bound to one datastore. */",
    "export class RecordsClient extends BaseClient {",
    ...methods,
    "}",
    "",
  ].join("\n").replace(/\n\n}\n$/, "\n}\n");
}

