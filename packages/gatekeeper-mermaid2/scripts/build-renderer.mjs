import { build } from 'esbuild';
import { readFile, writeFile, mkdir, copyFile, readdir, rm } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const generated = join(root, 'src/generated');
await mkdir(generated, { recursive: true });
// Inline the converter's bytes in its worker, so no network access is needed from workers.
const wasm = (await readFile(join(generated, 'converter.wasm'))).toString('base64');
const worker = (await readFile(join(root, 'src/converter.worker.js'), 'utf8'))
  .replace("import './generated/wasm_exec.js';", "import './wasm_exec.js';")
  .replace("  const response = await fetch(new URL('./generated/converter.wasm', import.meta.url));\n  if (!response.ok) throw new Error('Could not load the Mermaid converter.');", "  const bytes = Uint8Array.from(atob(CONVERTER_WASM), char => char.charCodeAt(0));")
  .replace('await response.arrayBuffer()', 'bytes');
const compiled = await build({ stdin: { contents: worker, resolveDir: generated, loader: 'js' }, bundle: true, write: false, minify: true, format: 'esm', define: { CONVERTER_WASM: JSON.stringify(wasm) } });
await writeFile(join(generated, 'converter-inline.js'), compiled.outputFiles[0].text);
const out = join(root, 'dist-renderer');
await rm(out, { recursive: true, force: true });
await build({ entryPoints: [join(root, 'renderer/main.js')], outdir: out, bundle: true, splitting: true, format: 'esm', minify: true, target: 'es2022', entryNames: '[name]', chunkNames: 'assets/[name]-[hash]' });
// Worker URLs are resolved by esbuild without Vite's worker plugin. Serve the worker as a Blob
// embedded in the main module rather than fetching from its opaque worker origin.
const inline = compiled.outputFiles[0].text;
const mainPath = join(out, 'main.js');
let main = await readFile(mainPath, 'utf8');
const urlPattern = /new Worker\(new URL\([^)]*converter-inline\.js[^)]*\),\{type:"module"\}\)/;
if (!urlPattern.test(main)) throw new Error('Converter worker URL changed; inspect the renderer build.');
main = main.replace(urlPattern, () => `new Worker(URL.createObjectURL(new Blob([${JSON.stringify(inline)}],{type:"text/javascript"})),{type:"module"})`);
await writeFile(mainPath, main);
await writeFile(join(out, 'index.html'), '<!doctype html><html><head><meta charset="utf-8"></head><body><script type="module" src="/main.js"></script></body></html>');
await mkdir(join(out, 'licenses'), { recursive: true });
for (const name of await readdir(join(root, 'public/licenses'))) await copyFile(join(root, 'public/licenses', name), join(out, 'licenses', name));
const skills = {};
for (const id of ['mermaid2-connector','mermaid2-blueprint','d2-authoring']) skills[id] = await readFile(join(root, 'skills', id, 'SKILL.md'), 'utf8');
await writeFile(join(generated, 'metadata.ts'), `// Generated by build-renderer.mjs.\nexport const TYPES_CODE = ${JSON.stringify(await readFile(join(root, 'src/types.d.ts'), 'utf8'))};\nexport const SKILLS = ${JSON.stringify(skills)};\n`);
console.log('Built private renderer assets and bundled skills. Main gzip bytes:', gzipSync(main).length);

const configurator = await build({ entryPoints: [join(root, 'src/configurator.js')], bundle: true, write: false, minify: true, format: 'esm' });
const configuratorHtml = '<!doctype html><html><body style="font:14px system-ui;padding:20px"><h2>MermaiD2 renderer</h2><p>Convert and lay out supplied Mermaid or D2. Rendering is ephemeral; external images and file imports are blocked. Cloudflare browser usage applies.</p><script type="module" src="data:text/javascript;base64,' + Buffer.from(configurator.outputFiles[0].text).toString('base64') + '"></script></body></html>';
await writeFile(join(generated, 'configurator.ts'), `// Generated by build-renderer.mjs.\nexport const CONFIGURATOR_HTML = ${JSON.stringify(configuratorHtml)};\n`);
