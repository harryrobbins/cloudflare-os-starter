// Bundles src/configurator/configurator.js into a self-contained HTML string at
// src/configurator/html.ts (written only when it changes).
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";

const bundle = await build({ entryPoints: [new URL("../src/configurator/configurator.js", import.meta.url).pathname], bundle: true, format: "iife", minify: true, write: false });
const css = "body{font:14px/1.45 system-ui,sans-serif;margin:0;padding:16px 18px;color:#172033}input[type=search]{width:100%;box-sizing:border-box;padding:8px;margin:4px 0 10px}" +
  ".row{display:flex;gap:8px;align-items:flex-start;padding:6px 0;border-bottom:1px solid #e5e8ef}.muted{color:#526079}.error{color:#b42318}.label{font-weight:600;margin:12px 0 4px}" +
  "#scopes label{display:block;padding:3px 0}#list{max-height:220px;overflow:auto}";
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><style>${css}</style></head><body>` +
  `<label for="q" style="font-weight:600">Datastore</label><input id="q" type="search" placeholder="Search your datastores" autocomplete="off">` +
  `<div id="list" role="radiogroup" aria-label="Datastores"></div><p id="status" class="muted" role="status"></p><div id="scopes"></div>` +
  `<script>${bundle.outputFiles[0].text.replaceAll("</script", "<\\/script")}</script></body></html>`;
const out = new URL("../src/configurator/html.ts", import.meta.url);
const text = `// Generated by scripts/build-configurator.mjs\nexport const CONFIGURATOR_HTML = ${JSON.stringify(html)};\n`;
const previous = await readFile(out, "utf8").catch(() => "");
if (previous !== text) await writeFile(out, text);
